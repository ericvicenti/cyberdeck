import { chromium } from "playwright";
const token = (await Bun.file(`${process.env.HOME}/.cyberdeck/token`).text()).trim();
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
const page = await ctx.newPage();
await page.goto("http://127.0.0.1:4777/#/desk");
await page.evaluate((t) => localStorage.setItem("cyberdeck-token", t), token).catch(() => {});
await page.reload();
await page.waitForTimeout(4000);
const talk = await page.locator("text=TALK").first().isVisible().catch(() => false);
const body = (await page.textContent("body")) ?? "";
const cfg = await page.evaluate(async (t) => (await fetch("/api/voice/config", { headers: { Authorization: `Bearer ${t}` } })).json(), token);
console.log(JSON.stringify({ talk, configured: cfg.configured, snippet: body.slice(0, 300) }));
await b.close();
